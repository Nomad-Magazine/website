// Install Playwright and axe outside the repository; see docs/directory-owner-workspace.md.
const { chromium } = require('playwright')
const AxeBuilder = require('@axe-core/playwright').default
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.DIRECTORY_TEST_URL || 'http://localhost:3000'
assert(['localhost', '127.0.0.1'].includes(new URL(base).hostname), 'Only local test apps are allowed')
const fixture = JSON.parse(fs.readFileSync('/tmp/nomad-owner-fixtures.json', 'utf8'))
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const owner = await browser.newContext({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 })
  const page = await owner.newPage()
  await page.goto(base + fixture.accounts.owner.callback)
  await page.waitForURL(base + '/console/')
  assert(await page.getByRole('heading', { name: 'Make your next connection.' }).isVisible())
  await owner.storageState({ path: '/tmp/nomad-owner-browser-state.json' })
  const publicResponse = await page.request.get(base + '/nomad_directory/')
  assert.equal(publicResponse.status(), 200)
  const publicHtml = await publicResponse.text()
  assert(publicHtml.includes('Roam House Madeira'))
  assert(publicHtml.includes('Our new workspace is open'))
  assert(publicHtml.includes('We have opened a quiet workspace'))
  const categoryResponse = await page.request.get(base + '/nomad_directory/coliving/')
  assert.equal(categoryResponse.status(), 200)
  assert((await categoryResponse.text()).includes('Roam House Madeira'))
  const csrf = await page.request.post(base + '/console/', { headers: { origin: 'https://attacker.example' }, form: { legacy_id: 'anything' } })
  assert.equal(csrf.status(), 403)
  const shot = async (name, route, mobile = false) => {
    if (route) await page.goto(base + route)
    await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1100 })
    await page.addStyleTag({ content: 'astro-dev-toolbar{display:none!important}' })
    await page.evaluate(() => document.fonts.ready)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${name} overflow`)
    const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    assert.deepEqual(
      audit.violations.map((v) => ({ id: v.id, nodes: v.nodes.map((n) => n.target) })),
      [],
      `${name} accessibility`,
    )
    await page.screenshot({ path: `/tmp/nomad-${name}.png`, fullPage: true })
  }
  await shot('owner-dashboard', '/console/')
  await shot('owner-dashboard-mobile', null, true)
  await shot('owner-listing', `/console/directory-submission/?id=${fixture.listingId}`)
  // Save a real new draft through the form, reload, and submit it for review.
  await page.goto(base + '/console/directory-submission/?new=1')
  await page.getByLabel('Business name', { exact: true }).fill('Nomad Field Notes')
  await page.getByLabel('Category', { exact: true }).selectOption({ label: 'App' })
  await page.getByLabel('Website (HTTPS)').fill('https://example.com/field-notes/')
  await page.getByLabel('Location', { exact: true }).fill('Worldwide')
  await page.getByLabel('Description', { exact: true }).fill('A travel journal for remote workers to remember useful places, local recommendations and new connections.')
  const logos = JSON.parse(fs.readFileSync('src/utils/directory-logo-files.json'))
  await page.getByLabel('Business logo (optional)').setInputFiles(`public/images/directory-logos/${logos[0]}`)
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.waitForURL(/saved=1/)
  assert(await page.getByRole('status').isVisible())
  await page.reload()
  assert.equal(await page.getByLabel('Business name', { exact: true }).inputValue(), 'Nomad Field Notes')
  assert((await page.getByAltText('Current business logo').getAttribute('src')).includes('/storage/v1/object/public/directory-owner-logos/'))
  const listingId = new URL(page.url()).searchParams.get('id')
  await page.getByRole('button', { name: 'Submit for review', exact: true }).click()
  await page.waitForURL(/saved=1/)
  assert((await page.getByRole('status').textContent()).includes('Submitted for review'))
  await page.goto(base + `/console/updates/?listing=${fixture.listingId}`)
  await page.getByLabel('Update title').fill('Winter community dinners are back')
  await page.getByLabel('Your update', { exact: true }).fill('Join our weekly dinners this winter to share stories, meet new neighbours and discover local food together.')
  await page.getByRole('button', { name: 'Submit for review', exact: true }).click()
  await page.waitForURL(/saved=1/)
  await shot('owner-updates', '/console/updates/')
  await page.goto(base + `/console/affiliates/?id=${fixture.affiliateId}`)
  await page.getByLabel('Attribution window').fill('45 days')
  await page.getByRole('button', { name: 'Submit for review', exact: true }).click()
  await page.waitForURL(/saved=1/)
  await shot('owner-affiliates', `/console/affiliates/?id=${fixture.affiliateId}`)
  await shot('owner-affiliates-mobile', null, true)
  const admin = await browser.newContext({ viewport: { width: 1440, height: 1100 } })
  const review = await admin.newPage()
  await review.goto(base + fixture.accounts.reviewer.callback)
  await review.waitForURL(base + '/console/')
  await review.goto(base + '/console/admin/directory/')
  assert(await review.getByRole('heading', { name: 'Nomad Field Notes', exact: true }).isVisible())
  await review.addStyleTag({ content: 'astro-dev-toolbar{display:none!important}' })
  await review.screenshot({ path: '/tmp/nomad-owner-review.png', fullPage: true })
  await review.getByRole('form', { name: 'Review Nomad Field Notes', exact: true }).getByRole('button', { name: 'Approve and publish' }).click()
  await review.waitForURL(/saved=1/)
  const published = await page.request.get(base + '/nomad_directory/')
  assert((await published.text()).includes(`listing-${listingId}`))
  await page.goto(base + '/console/')
  assert((await page.locator('body').textContent()).includes('Nomad Field Notes'))
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.waitForURL(base + '/nomad-directory-edit/')
  await page.goto(base + '/console/')
  await page.waitForURL(base + '/nomad-directory-edit/')
  await browser.close()
  console.log(
    'PASS: real magic-link session, authenticated pages, form draft persistence, listing/update/affiliate submission, reviewer approval, immediate public/category rendering, CSRF rejection, signout, desktop/mobile layout and WCAG AA. Screenshots captured from local Supabase data.',
  )
})().catch((error) => {
  console.error(error)
  process.exit(1)
})
