const { chromium } = require('playwright')
const AxeBuilder = require('@axe-core/playwright').default
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const base = process.env.DIRECTORY_TEST_URL || 'http://localhost:3000'
const mail = process.env.DIRECTORY_TEST_MAIL_URL || 'http://127.0.0.1:54324'
for (const url of [base, mail]) assert(['localhost', '127.0.0.1'].includes(new URL(url).hostname), 'Local fixtures only')
;(async () => {
  const f = JSON.parse(await fs.readFile('/tmp/nomad-vote-fixtures.json', 'utf8'))
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const button = () => page.locator(`[data-upvote="${f.target}"]`)
    const waitVote = value => page.waitForFunction(({ id, value }) => document.querySelector(`[data-upvote="${id}"]`)?.getAttribute('aria-pressed') === String(value), { id: f.target, value })
    const count = async () => Number(await button().locator('[data-vote-count]').textContent())
    await page.goto(`${base}/nomad_directory/#listing-${f.target}`)
    await waitVote(false)
    const initial = await count()
    await button().click()
    await page.waitForURL('**/nomad-directory-edit/**')
    assert(await page.getByRole('heading', { name: 'Sign in to upvote', exact: true }).isVisible())
    const loginAudit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    assert.deepEqual(loginAudit.violations.map(v => v.id), [])
    assert.match(await page.locator('meta[name=robots]').getAttribute('content'), /noindex/)
    await page.evaluate(() => document.fonts.ready)
    await page.screenshot({ path: '/tmp/nomad-votes-login.png' })
    const email = `directory-voting-signup-${Date.now()}@example.test`
    await page.getByRole('textbox', { name: 'Email address' }).fill(email)
    await page.getByRole('button', { name: 'Send login link', exact: true }).click()
    await page.getByRole('status').filter({ hasText: `Check ${email}` }).waitFor()
    let message
    for (let n = 0; n < 20; n++) {
      const inbox = await fetch(mail + '/api/v1/messages').then(r => r.json())
      message = inbox.messages.find(m => m.To.some(to => to.Address === email))
      if (message) break
      await new Promise(resolve => setTimeout(resolve, 200))
    }
    assert(message, 'Local login email delivered')
    const detail = await fetch(`${mail}/api/v1/message/${message.ID}`).then(r => r.json())
    const loginLink = detail.HTML.match(/href="([^"]*\/auth\/v1\/verify[^\"]+)"/)[1].replaceAll('&amp;', '&')
    await page.goto(loginLink)
    await page.waitForURL('**/nomad_directory/vote/**')
    assert(await page.getByRole('button', { name: 'Confirm upvote', exact: true }).isVisible())
    const confirmationAudit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    assert.deepEqual(confirmationAudit.violations.map(v => v.id), [])
    assert.match(await page.locator('meta[name=robots]').getAttribute('content'), /noindex/)
    await page.getByRole('button', { name: 'Confirm upvote', exact: true }).click()
    await page.waitForURL(`**/nomad_directory/**#listing-${f.target}`)
    await waitVote(true)
    assert.equal(await count(), initial + 1)
    // Own vote persists after reload and can be removed by keyboard.
    await page.reload(); await waitVote(true)
    await button().focus(); await page.keyboard.press('Space'); await waitVote(false)
    assert.equal(await count(), initial)
    await page.reload(); await waitVote(false)
    // Another signed-in account retains its own vote.
    const other = await browser.newContext()
    const otherPage = await other.newPage()
    await otherPage.goto(`${base}/auth/callback/?${new URLSearchParams({ token_hash: f.tokenHash, type: 'magiclink', next: `/nomad_directory/#listing-${f.target}` })}`)
    await otherPage.waitForFunction(id => document.querySelector(`[data-upvote="${id}"]`)?.getAttribute('aria-pressed') === 'true', f.target)
    await other.close()
    // Failed writes show an error without changing the vote/count, then retry succeeds.
    await page.route('**/api/directory-votes/', route => route.request().method() === 'POST' ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Your vote could not be saved. Please try again.' }) }) : route.continue())
    await button().click()
    await page.getByRole('alert').filter({ hasText: 'Your vote could not be saved' }).waitFor()
    assert.equal(await button().getAttribute('aria-pressed'), 'false')
    assert.equal(await count(), initial)
    await page.unroute('**/api/directory-votes/')
    await button().click(); await waitVote(true)
    assert.equal(await page.locator('[data-vote-error]').count(), 0)
    const state = await page.request.get(base + '/api/directory-votes/')
    assert.match(state.headers()['cache-control'], /no-store/)
    assert.deepEqual((await state.json()).votes, [f.target])
    assert.equal((await page.request.post(base + '/api/directory-votes/', { headers: { Origin: 'https://example.invalid' }, data: { listing_id: f.target, voted: false } })).status(), 403)
    assert.equal((await page.request.post(base + '/api/directory-votes/', { headers: { Origin: base }, data: { listing_id: f.target, voted: 'yes' } })).status(), 400)
    assert.equal((await page.request.post(base + '/api/directory-votes/', { headers: { Origin: base }, data: { listing_id: 'not-published', voted: true } })).status(), 404)
    await page.locator('#sort-select').selectOption('votes')
    const values = await page.locator('[data-entry]:visible').evaluateAll(cards => cards.map(card => Number(card.dataset.votes)))
    assert.deepEqual(values, [...values].sort((a, b) => b - a))
    assert.equal(await page.locator('[data-entry]:visible').first().getAttribute('id'), `listing-${f.target}`)
    await page.locator('#directory-container').scrollIntoViewIfNeeded()
    await page.evaluate(() => scrollTo(0, document.querySelector('#sort-select').getBoundingClientRect().top + scrollY - 30))
    await page.evaluate(() => document.fonts.ready)
    await page.screenshot({ path: '/tmp/nomad-votes-directory.png' })
    let audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    assert.deepEqual(audit.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), [])
    await page.setViewportSize({ width: 390, height: 844 })
    await button().scrollIntoViewIfNeeded()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: '/tmp/nomad-votes-mobile.png' })
    const category = f.category.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
    await page.goto(`${base}/nomad_directory/${category}/#listing-${f.target}`)
    await waitVote(true)
    const pagesBefore = context.pages().length
    await button().click(); await waitVote(false)
    assert.equal(context.pages().length, pagesBefore, 'Voting must not open the business website')
    await button().click(); await waitVote(true)
    // Server-rendered fallback supports voting and removal with JavaScript disabled.
    const noJS = await browser.newContext({ javaScriptEnabled: false, storageState: await context.storageState() })
    const fallback = await noJS.newPage()
    await fallback.goto(`${base}/nomad_directory/#listing-${f.target}`)
    await fallback.locator(`[data-upvote="${f.target}"]`).click()
    await fallback.getByRole('button', { name: 'Remove my upvote', exact: true }).click()
    await fallback.waitForURL(`**/nomad_directory/**#listing-${f.target}`)
    await fallback.locator(`[data-upvote="${f.target}"]`).click()
    await fallback.getByRole('button', { name: 'Confirm upvote', exact: true }).click()
    await fallback.waitForURL(`**/nomad_directory/**#listing-${f.target}`)
    await noJS.close()
    // Login/callback destinations cannot leave the directory/site.
    const invalidNext = await page.request.get(base + '/nomad-directory-edit/?next=https%3A%2F%2Fevil.example%2F', { maxRedirects: 0 })
    assert.equal(invalidNext.headers().location, '/console/')
    await context.clearCookies()
    await button().click()
    await page.waitForURL('**/nomad-directory-edit/**')
    const anonymous = await page.request.post(base + '/api/directory-votes/', { headers: { Origin: base }, data: { listing_id: f.target, voted: true } })
    assert.equal(anonymous.status(), 401)
    assert.deepEqual(errors, [])
    console.log('PASS: real signup/email/PKCE return, confirm/add/remove/reload, keyboard input, account isolation, failed-write retry, CSRF, expired session, vote ranking, category clicks, no-JavaScript voting, mobile layout and WCAG AA. Screenshots captured using local test votes.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
