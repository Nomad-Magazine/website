const {chromium}=require('playwright')
const AxeBuilder=require('@axe-core/playwright').default
const assert=require('node:assert/strict')
const fs=require('node:fs/promises')
const base=process.env.DIRECTORY_TEST_URL || 'http://localhost:3000'
assert(['localhost','127.0.0.1'].includes(new URL(base).hostname),'Local fixtures only')
;(async()=>{
 const fixtures=JSON.parse(await fs.readFile('/tmp/nomad-award-fixtures.json','utf8'))
 const browser=await chromium.launch({channel:'chrome',headless:true})
 try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']})
  const page=await context.newPage(),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  const audit=async()=>{const report=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();assert.deepEqual(report.violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)})),[])}
  const metadata=async()=>{
   assert.equal(await page.locator('h1').count(),1)
   const title=await page.title(),description=await page.locator('meta[name=description]').getAttribute('content')
   assert(title.length>=50&&title.length<=60,`Title length ${title.length}: ${title}`)
   assert(description.length>=150&&description.length<=160,`Description length ${description.length}`)
   assert((await page.locator('link[rel=canonical]').getAttribute('href')).endsWith('/'))
  }
  for(const kind of ['day','week','month','year']) {
   const response=await page.goto(`${base}/nomad_directory/awards/?period=${kind}`)
   assert.equal(response.status(),200);await metadata()
   assert(await page.getByRole('heading',{name:'Nomad Grove',exact:true}).first().isVisible())
   const badge=page.locator('img[src*="badge.svg/"]').first()
   await badge.scrollIntoViewIfNeeded();await badge.evaluate(img=>img.decode())
   assert.equal(await badge.evaluate(img=>img.naturalWidth),360)
  }
  await page.goto(`${base}/nomad_directory/awards/`);await audit();await page.evaluate(()=>document.fonts.ready)
  await page.screenshot({path:'/tmp/nomad-awards-winners.png'})
  const award=fixtures.awards.find(a=>a.kind==='month')
  const resultPath=`/nomad_directory/awards/${award.id}/`
  await page.goto(base+resultPath);await metadata();await audit()
  await page.getByRole('button',{name:'Copy embed code',exact:true}).click()
  const embed=await page.locator('textarea').inputValue()
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),embed)
  assert(embed.includes(`https://nomad-magazine.com${resultPath}`))
  assert(embed.includes('rel="noopener noreferrer"')&&embed.includes('width="360"')&&!embed.includes('<script'))
  await page.evaluate(()=>scrollTo(0,document.querySelector('main').getBoundingClientRect().top+scrollY))
  await page.screenshot({path:'/tmp/nomad-awards-result.png'})
  const badgeResponse=await page.request.get(base+resultPath+'badge.svg/')
  assert.equal(badgeResponse.status(),200);assert.match(badgeResponse.headers()['content-type'],/image\/svg\+xml/)
  assert.match(badgeResponse.headers()['content-security-policy'],/default-src 'none'/)
  const markup=await badgeResponse.text()
  assert(markup.includes('Monthly winner')&&markup.includes('Nomad Grove')&&!markup.includes('<script'))
  const embedPage=await context.newPage()
  await embedPage.setContent(embed.replaceAll('https://nomad-magazine.com',base))
  await embedPage.locator('img').evaluate(img=>img.decode())
  assert.equal(await embedPage.locator('img').evaluate(img=>img.naturalWidth),360)
  const [verification]=await Promise.all([context.waitForEvent('page'),embedPage.locator('a').click()])
  await verification.waitForURL(base+resultPath);await verification.close();await embedPage.close()
  const xml=await (await page.request.get(base+'/nomad_directory/awards/sitemap/')).text()
  assert(xml.includes(`https://nomad-magazine.com${resultPath}`))
  assert(!xml.includes(fixtures.revoked))
  assert((await (await page.request.get(base+'/sitemap-index.xml')).text()).includes('/nomad_directory/awards/sitemap/'))
  assert.equal((await page.request.get(base+'/nomad_directory/awards/00000000-0000-0000-0000-000000000000/badge.svg/')).status(),404)
  assert.equal((await page.request.get(base+`/nomad_directory/awards/${fixtures.revoked}/badge.svg/`)).status(),410)
  await page.goto(base+`/nomad_directory/awards/${fixtures.revoked}/`)
  assert(await page.getByRole('heading',{name:'This award has been withdrawn',exact:true}).isVisible())
  assert.equal(await page.locator('[data-copy-badge]').count(),0)
  // Owner library contains only owned listings; changing a query cannot select someone else's badges.
  const badgeLogin=await page.request.get(base+'/console/badges/',{maxRedirects:0})
  assert.equal(badgeLogin.headers().location,'/nomad-directory-edit/?next=%2Fconsole%2Fbadges%2F')
  await page.goto(`${base}/auth/callback/?${new URLSearchParams({token_hash:fixtures.tokens.owner,type:'magiclink',next:'/console/badges/'})}`)
  await page.waitForURL(base+'/console/badges/')
  assert(await page.getByRole('heading',{name:'Nomad Grove',exact:true}).first().isVisible())
  assert.equal(await page.getByRole('heading',{name:'Atlas House',exact:true}).count(),0)
  await audit();await page.screenshot({path:'/tmp/nomad-awards-owner.png'})
  await page.goto(base+`/console/badges/?listing=${fixtures.atlas}`)
  assert.equal(await page.getByRole('heading',{name:'Atlas House',exact:true}).count(),0)
  const denied=await page.request.get(base+'/console/admin/awards/',{maxRedirects:0})
  assert.equal(denied.headers().location,'/console/')
  await page.setViewportSize({width:390,height:844});await page.goto(base+'/console/badges/')
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));await audit()
  await page.screenshot({path:'/tmp/nomad-awards-owner-mobile.png'})
  await page.goto(base+'/nomad_directory/awards/')
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));await audit()
  await page.screenshot({path:'/tmp/nomad-awards-winners-mobile.png'})
  // Reviewer can withdraw an older fixture award; the official asset immediately stops issuing it.
  const reviewerContext=await browser.newContext(),reviewerPage=await reviewerContext.newPage()
  await reviewerPage.goto(`${base}/auth/callback/?${new URLSearchParams({token_hash:fixtures.tokens.reviewer,type:'magiclink'})}`)
  await reviewerPage.waitForURL(base+'/console/');await reviewerPage.goto(base+'/console/admin/awards/')
  const candidate=fixtures.awards.filter(a=>a.kind==='week').at(-1)
  const form=reviewerPage.locator(`form:has(input[name="award_id"][value="${candidate.id}"])`)
  await form.getByLabel('Private reason for withdrawal').fill('Local review test for an invalid award.')
  await form.getByRole('button',{name:'Withdraw this award',exact:true}).click()
  await reviewerPage.getByRole('status').filter({hasText:'Award withdrawn'}).waitFor()
  assert.equal((await reviewerPage.request.get(base+`/nomad_directory/awards/${candidate.id}/badge.svg/`)).status(),410)
  assert.equal((await reviewerPage.request.post(base+'/console/admin/awards/',{headers:{Origin:'https://example.invalid'},form:{award_id:award.id,reason:'Forged cross-origin request'}})).status(),403)
  await reviewerContext.close()
  const noJS=await browser.newContext({javaScriptEnabled:false}),fallback=await noJS.newPage()
  await fallback.goto(base+resultPath);assert(await fallback.locator('textarea').isVisible())
  assert((await fallback.locator('textarea').inputValue()).includes('<img'));await noJS.close()
  assert.deepEqual(errors,[])
  console.log('PASS: all four winner periods, canonical/metadata, real SVG loading and external embed verification, clipboard copy, mobile/accessibility, owner isolation, reviewer withdrawal, CSRF, sitemap, missing/revoked badges and no-JavaScript embed fallback. Local fixture screenshots captured.')
 } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)})
